#!/usr/bin/env python3
"""Unit tests for scripts/docs_index.py, on a temporary documentation tree."""
import contextlib
import io
import os
import pathlib
import sys
import tempfile
import unittest

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import docs_index  # noqa: E402


def write(root: pathlib.Path, relative: str, text: str) -> None:
    path = root / relative
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def run(*argv: str) -> tuple[int, str, str]:
    out, err = io.StringIO(), io.StringIO()
    with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
        status = docs_index.main(list(argv))
    return status, out.getvalue(), err.getvalue()


class DocsIndexTests(unittest.TestCase):
    def setUp(self) -> None:
        temporary = tempfile.TemporaryDirectory()
        self.addCleanup(temporary.cleanup)
        self.root = pathlib.Path(temporary.name)
        write(self.root, "docs/ARCHITECTURE.md", "---\nstatus: active\nsummary: The architecture.\n---\n# Architecture\n")
        write(self.root, "docs/reference/zeta.md", "---\nsummary: \"Quoted: with a colon.\"\nsourceOfTruth:\n  - a.py\n---\n# Zeta\n")
        write(self.root, "docs/reference/alpha.md", "---\nstatus: active\nsummary: Alpha\n  continues here.\n---\n# Alpha\n")
        write(self.root, "docs/audits/2026-01-01-audit.md", "---\nstatus: historical\n---\n\n## The audit heading ##\n")
        write(self.root, "docs/audits/archive/old/note.md", "```\n# not a heading\n```\n# Archived note\n")
        write(self.root, "docs/audits/archive/old/ledger.json", "{}\n")
        write(self.root, "docs/releases/v1.0.0.md", "# Vocello 1.0.0\n\nNotes.\n")
        write(self.root, "docs/ROADMAP.md", "# Roadmap\n")
        write(self.root, "docs/elsewhere/ignored.md", "# Ignored\n")

    def test_render_lists_each_document_once_grouped_and_sorted(self) -> None:
        text = docs_index.render(self.root)
        self.assertEqual(text, "\n".join([
            "# Documentation index",
            "",
            "> Generated by `python3 scripts/docs_index.py render`. Do not edit manually.",
            "> Each line is a document's front-matter `summary`, or its first heading when it has none.",
            "",
            "6 documents.",
            "",
            "## docs",
            "",
            "- [ARCHITECTURE.md](ARCHITECTURE.md): The architecture.",
            "",
            "## docs/reference",
            "",
            "- [alpha.md](reference/alpha.md): Alpha continues here.",
            "- [zeta.md](reference/zeta.md): Quoted: with a colon.",
            "",
            "## docs/audits",
            "",
            "- [2026-01-01-audit.md](audits/2026-01-01-audit.md): The audit heading",
            "",
            "## docs/audits/archive/old",
            "",
            "- [note.md](audits/archive/old/note.md): Archived note",
            "",
            "## docs/releases",
            "",
            "- [v1.0.0.md](releases/v1.0.0.md): Vocello 1.0.0",
            "",
        ]))

    def test_render_writes_and_check_passes_then_fails_when_stale(self) -> None:
        self.assertEqual(run("--check", "--root", str(self.root))[0], 1, "a missing index is stale")
        status, out, _ = run("render", "--root", str(self.root))
        self.assertEqual((status, out), (0, "Wrote docs/INDEX.md\n"))
        self.assertEqual(run("render", "--check", "--root", str(self.root))[0], 0)
        self.assertEqual(run("--check", "--root", str(self.root))[0], 0)

        write(self.root, "docs/decisions/new.md", "---\nsummary: A new decision.\n---\n")
        status, _, err = run("render", "--check", "--root", str(self.root))
        self.assertEqual(status, 1)
        self.assertIn("docs/INDEX.md is stale", err)
        self.assertNotIn("A new decision.", (self.root / "docs/INDEX.md").read_text(encoding="utf-8"),
                         "--check never writes")

        self.assertEqual(run("render", "--root", str(self.root))[0], 0)
        self.assertIn("- [new.md](decisions/new.md): A new decision.",
                      (self.root / "docs/INDEX.md").read_text(encoding="utf-8"))
        self.assertEqual(run("--check", "--root", str(self.root))[0], 0)

    def test_a_changed_summary_makes_the_index_stale(self) -> None:
        run("render", "--root", str(self.root))
        write(self.root, "docs/reference/alpha.md", "---\nsummary: Alpha, reworded.\n---\n# Alpha\n")
        self.assertEqual(run("--check", "--root", str(self.root))[0], 1)

    def test_a_document_with_nothing_to_show_is_an_error(self) -> None:
        write(self.root, "docs/reference/empty.md", "---\nstatus: active\n---\nNo heading here.\n")
        status, _, err = run("render", "--root", str(self.root))
        self.assertEqual(status, 2)
        self.assertIn("empty.md: has no front-matter summary and no heading", err)
        self.assertFalse((self.root / "docs/INDEX.md").exists())

    def test_front_matter_reads_scalars_and_skips_lists(self) -> None:
        fields, body = docs_index.front_matter(
            "---\nstatus: active\nsummary: 'It''s one line.'\nsourceOfTruth:\n  - scripts/x.py\nreviewed: 2026-11-15\n---\nBody\n")
        self.assertEqual(fields["status"], "active")
        self.assertEqual(docs_index.unquoted(fields["summary"]), "It's one line.")
        self.assertEqual(fields["sourceOfTruth"], "")
        self.assertEqual(fields["reviewed"], "2026-11-15")
        self.assertEqual(body, "Body")
        self.assertEqual(docs_index.front_matter("# No front matter\n"), ({}, "# No front matter\n"))
        self.assertEqual(docs_index.front_matter("---\nsummary: unterminated\n")[0], {})


if __name__ == "__main__":
    unittest.main()
